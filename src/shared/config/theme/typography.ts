export type TypographyTokenKey = keyof typeof TYPOGRAPHY_TOKENS

export const FONT_FAMILY = {
  sans: "'Plus Jakarta Sans Variable', 'Plus Jakarta Sans', -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif",
  heading: "var(--font-sans)",
} as const

/**
 * Mendapatkan inline CSS style object untuk token typography tertentu.
 */
export function getTypographyStyle(key: TypographyTokenKey): React.CSSProperties {
  const token = TYPOGRAPHY_TOKENS[key]
  if (!token) return {}
  return {
    fontFamily: FONT_FAMILY.sans,
    fontSize: `${token.size}px`,
    lineHeight: `${token.lineHeight}px`,
    fontWeight: token.weight,
    letterSpacing: `${token.letterSpacing}px`,
  }
}
